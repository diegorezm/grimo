// Points `@grimo/premium/tokens|web|mobile` at the paid content when the private repository is
// checked out in `packages/premium/private` (a git submodule), and at the empty stubs when it is
// not. Runs on install (root `postinstall`); run `pnpm premium:link` after adding or removing it.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src", "content");
mkdirSync(out, { recursive: true });

const parts = [
  { name: "tokens", symbol: "tokens", ext: "ts" },
  { name: "web", symbol: "platform", ext: "tsx" },
  { name: "mobile", symbol: "platform", ext: "tsx" },
];
let linked = 0;
for (const { name, symbol, ext } of parts) {
  const has = existsSync(join(root, "private", "src", `${name}.${ext}`));
  if (has) linked++;
  const from = has ? `../../private/src/${name}` : `../empty/${name}`;
  const body = `// Generated by scripts/link.mjs. Do not edit.\nexport { ${symbol} } from "${from}";\n`;
  const file = join(out, `${name}.ts`);
  if (!existsSync(file) || readFileSync(file, "utf8") !== body) writeFileSync(file, body);
}
console.log(
  linked > 0
    ? "@grimo/premium: paid content linked"
    : "@grimo/premium: no paid content (free build)",
);
